/**
 * Publishes the "AI SEO for <trade>" landing pages from handoff/ai-seo/pages
 * into public/ai-seo-for-<slug>/index.html.
 *
 * The pages are standalone HTML documents with their own stylesheet — they do
 * not use the Astro layout — so they ship through public/ untouched by the
 * build. This script applies the handoff's pre-publish steps (README §"Before
 * publishing") plus the fixes that only make sense once the pages live on this
 * site, and it is re-runnable: regenerate the pages from the template, drop
 * them in handoff/ai-seo/pages, and run `npm run build:ai-seo` again.
 *
 * What it changes, and why:
 *  1. Strips the build-notes block, which is internal and not part of the page.
 *  2. Rewrites the relative img/ paths to /ai-seo/img/ — one shared image
 *     folder for all 36 pages instead of a copy per directory.
 *  3. Repoints the auth/checkout CTAs. The handoff assumes /signin/ and
 *     /signup/?plan=<tier>; this site has neither — sign-in is a separate
 *     subdomain and trials go straight to Stripe checkout. Left as-is, every
 *     pricing CTA on all 36 pages would 404.
 *  4. Adds noindex to pages whose screenshots are still missing, and keeps the
 *     placeholder script that renders a "Screenshot pending" panel for them.
 *     A page with both captures present is treated as complete: it gets no
 *     robots tag, the placeholder script is dropped, and it enters the XML
 *     sitemap (see src/data/ai-seo-pages.js).
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { links } from '../src/lib/data.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'handoff/ai-seo/pages');
const OUT = join(root, 'public');
const IMG_DIR = join(root, 'public/ai-seo/img');

/**
 * Replaces the handoff's placeholder script. That one only attached an `error`
 * listener, which never fires for an image that already failed by the time the
 * script at the end of <body> runs — so the pending pages rendered a broken
 * image icon instead of the panel. Checking naturalWidth covers that case.
 */
const PENDING_SCRIPT = `<script>
document.querySelectorAll('img[data-pending]').forEach(function (img) {
  function pending() {
    var fig = img.closest('figure');
    if (fig) fig.innerHTML = '<div class="shot-pending">Screenshot pending<br>Capture ' + img.getAttribute('data-pending') + '<br>Save as ' + img.getAttribute('src') + '</div>';
  }
  if (img.complete && img.naturalWidth === 0) pending();
  else img.addEventListener('error', pending);
});
</script>`;

/** The handoff's own version, matched so it can be swapped or dropped. */
const HANDOFF_SCRIPT = /<script>\s*document\.querySelectorAll\('img\[data-pending\]'\)[\s\S]*?<\/script>/g;

/** Handoff CTA target -> where it actually lives on this site. */
const LINK_MAP = {
  '/signin/': links.signIn,
  '/signup/?plan=lite': links.liteTrial,
  '/signup/?plan=plus': links.plusTrial,
  '/signup/?plan=max': links.maxTrial,
};

const shipped = [];

for (const file of readdirSync(SRC).filter((f) => f.endsWith('.html')).sort()) {
  const slug = file.replace(/^ai-seo-for-|\.html$/g, '');
  let html = readFileSync(join(SRC, file), 'utf8');

  // 1. Internal build notes never ship.
  html = html.replace(/<section class="notes">[\s\S]*?<\/section>\s*/g, '');

  // 2. One shared image folder rather than 36 copies of the same captures.
  html = html.replace(/src="img\//g, 'src="/ai-seo/img/');

  // 3. Auth + checkout CTAs -> this site's real destinations.
  for (const [from, to] of Object.entries(LINK_MAP)) {
    html = html.split(`href="${from}"`).join(`href="${to}"`);
  }

  // 4. A page is complete only when both of its captures exist on disk.
  const shots = [...html.matchAll(/<img[^>]*src="\/ai-seo\/img\/([^"]+)"/g)].map((m) => m[1]);
  const missing = shots.filter((s) => !existsSync(join(IMG_DIR, s)));

  if (missing.length) {
    html = html.replace(
      /(<meta name="viewport"[^>]*>)/,
      '$1\n<meta name="robots" content="noindex, follow">'
    );
    html = html.replace(HANDOFF_SCRIPT, PENDING_SCRIPT);
  } else {
    // Nothing left to fall back to — drop the placeholder script.
    html = html.replace(new RegExp(HANDOFF_SCRIPT.source + '\\s*', 'g'), '');
  }

  const dir = join(OUT, `ai-seo-for-${slug}`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'index.html'), html);
  shipped.push({ slug, indexed: missing.length === 0, missing });
}

// The page list feeds the XML sitemap and the HTML sitemap page.
const indexed = shipped.filter((p) => p.indexed);
const module = `// GENERATED by scripts/build-ai-seo-pages.mjs — do not edit by hand.
//
// The "AI SEO for <trade>" landing pages ship as static HTML from public/, so
// neither Astro's router nor @astrojs/sitemap can see them. This list is how
// the rest of the site finds them: astro.config.mjs feeds the indexed ones to
// the sitemap integration, and src/pages/sitemap.astro links them all.
//
// \`indexed: false\` means the page is still missing its screenshots and ships
// with a noindex tag. Add the two captures to public/ai-seo/img and re-run the
// script to promote it.
export const aiSeoPages = ${JSON.stringify(
  shipped.map(({ slug, indexed }) => ({ slug, indexed })),
  null,
  2
)};

export const aiSeoPath = (slug) => \`/ai-seo-for-\${slug}/\`;
`;
writeFileSync(join(root, 'src/data/ai-seo-pages.js'), module);

console.log(`${shipped.length} pages written to public/`);
console.log(`  indexed:  ${indexed.length} (${indexed.map((p) => p.slug).join(', ') || 'none'})`);
console.log(`  noindex:  ${shipped.length - indexed.length} (awaiting screenshots)`);
